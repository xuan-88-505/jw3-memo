type Tone = "#" | "+" | "*" | "%";

interface Run {
  x: number;
  y: number;
  w: number;
  tone: Tone;
}

/** 同一行里相邻的同色格子合成一个矩形，减少节点 */
function toRuns(grid: readonly string[]): Run[] {
  const runs: Run[] = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      let w = 1;
      while (row[x + w] === c) w++;
      if (c !== ".") runs.push({ x, y, w, tone: c as Tone });
      x += w;
    }
  });
  return runs;
}

const RUNS = Object.fromEntries(
  Object.entries(GRIDS).map(([k, g]) => [k, toRuns(g)])
) as Record<NavIconName, Run[]>;

const SHADE = 0.4;
const ACCENT = "var(--color-cinnabar)";

function paint(tone: Tone, active: boolean) {
  switch (tone) {
    case "#":
      return { fill: "currentColor" };
    case "+":
      return { fill: "currentColor", fillOpacity: SHADE };
    case "*":
      return active ? { fill: ACCENT } : { fill: "currentColor" };
    case "%":
      return active
        ? { fill: ACCENT }
        : { fill: "currentColor", fillOpacity: SHADE };
  }
}

export function NavIcon({
  name,
  active = false,
  className,
}: {
  name: NavIconName;
  active?: boolean;
  className?: string;
}) {
  return (
    <svg
      viewBox="0 0 16 16"
      width={16}
      height={16}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      {RUNS[name].map((r, i) => (
        <rect
          key={i}
          x={r.x}
          y={r.y}
          width={r.w}
          height={1}
          {...paint(r.tone, active)}
        />
      ))}
    </svg>
  );
}
